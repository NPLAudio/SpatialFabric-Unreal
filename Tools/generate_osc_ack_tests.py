"""Generate silent native OSC conformance cases from the shared ack-v1 fixture.

Use --check in CI; --fixture can override the sibling interop checkout location.
No Unreal process, network listener or audio device is started.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FIXTURE = ROOT.parents[2] / "SpatialFabric/Fixtures/ack-v1.json"
OUTPUT = ROOT / "Source/AudioLoom/Private/Tests/AudioLoomAckFixtures.inl"


def text(value):
    return "TEXT(" + json.dumps(value, ensure_ascii=False) + ")"


def render(fixture):
    lines = ["// Generated by Tools/generate_osc_ack_tests.py from Fixtures/ack-v1.json. Do not edit."]
    for row in fixture["decisions"]:
        args = []
        for tag, value in row["args"]:
            if tag == "f":
                args.append(f"UOSCManager::AddFloat(M, {float(value)}f);")
            elif tag == "i":
                args.append(f"UOSCManager::AddInt32(M, {value});")
            elif tag == "s":
                args.append(f"UOSCManager::AddString(M, {text(value)});")
            else:
                raise ValueError(f"Unsupported fixture tag: {tag}")
        lines.append("CheckDecision(%s, %s, [](FOSCMessage& M) { %s }, %s, %s);" % (
            str(row["kind"] == "live").lower(), text(row["op"]), " ".join(args),
            text(row["result"]), str(row["acts"]).lower()))
    for row in fixture["vectors"]:
        assert row["address"].endswith("/ack")
        lines.append("CheckPacket(%s, %s, %s, %s, %s, %s);" % (
            text(row["address"][:-4]), text(row["command"]), text(row["result"]),
            str(bool(row["playing"])).lower(), text(row["detail"]), text(row["hex"])))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", type=Path, default=DEFAULT_FIXTURE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    fixture = json.loads(args.fixture.read_text(encoding="utf-8"))
    generated = render(fixture)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Native OSC acknowledgement fixtures are stale; regenerate them")
        print(f"Matched {len(fixture['decisions'])} decisions and {len(fixture['vectors'])} golden packets")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
